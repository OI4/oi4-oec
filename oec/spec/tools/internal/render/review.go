// Paths of the generated review views of the matrix and the vectors.
const (
	MatrixView     = "matrix/view/method-resource.md"
	VectorViewDir  = "vectors/view"
	matrixToVector = "../../vectors/view/"
	vectorToReqs   = "../../requirements/view/"
	vectorToMatrix = "../../matrix/view/method-resource.md"
)

// ReviewViews returns the Markdown views of the Method x Resource matrix and
// of all vector files (relative path -> content).
func ReviewViews(s *catalog.Spec, ts *topic.Spec, files []vectors.File) map[string]string {
	areas := map[string]bool{}
	for _, f := range s.Files {
		areas[f.Area] = true
	}
	out := map[string]string{MatrixView: matrix(ts, files)}
	var idx strings.Builder
	idx.WriteString("<!-- Generated by 'spectool render' – do not edit. -->\n# OEC v2 test vectors\n\n")
	fmt.Fprintf(&idx, "Guideline baseline: `%s`. Source of truth: the YAML files in `oec/spec/vectors/` (ADR-0018); expected results are recomputed by `spectool lint`. Matrix view: [method-resource.md](%s).\n\n", s.Areas.Baseline, vectorToMatrix)
	idx.WriteString("| View | Source | Kind | Vectors | Valid | Invalid | Golden | Draft | Reviewed |\n|---|---|---|---:|---:|---:|---:|---:|---:|\n")
	for _, f := range files {
		name := vectorViewName(f.Path)
		out[VectorViewDir+"/"+name] = vectorFile(f, ts, areas)
		var valid, golden, draft, reviewed int
		for _, v := range f.Vectors {
			if v.Expected == "valid" {
				valid++
			}
			if v.Origin.Kind == "guideline" {
				golden++
			}
			switch v.Status {
			case "draft":
				draft++
			case "reviewed":
				reviewed++
			}
		}
		fmt.Fprintf(&idx, "| [%s](%s) | `%s` | %s | %d | %d | %d | %d | %d | %d |\n",
			strings.TrimSuffix(name, ".md"), name, f.Path, f.Kind, len(f.Vectors), valid, len(f.Vectors)-valid, golden, draft, reviewed)
	}
	idx.WriteString("\nGolden = taken from the guideline (`origin.kind: guideline`); all others are constructed. Vectors stay `draft` until the PO confirms them (G-3.9).\n")
	out[VectorViewDir+"/README.md"] = idx.String()
	return out
}

// vectorViewName maps "vectors/topic/valid.yaml" to "topic-valid.md".
func vectorViewName(p string) string {
	rel := strings.TrimPrefix(p, vectors.Dir+"/")
	return strings.ReplaceAll(strings.TrimSuffix(rel, path.Ext(rel)), "/", "-") + ".md"
}

func matrix(ts *topic.Spec, files []vectors.File) string {
	byRule := map[string][]string{}
	viewOf := map[string]string{}
	for _, f := range files {
		for _, v := range f.Vectors {
			if v.Parse != nil {
				byRule[v.Parse.Rule] = append(byRule[v.Parse.Rule], v.ID)
				viewOf[v.ID] = vectorViewName(f.Path)
			}
		}
	}
	var methods, resources []string
	seen := map[string]bool{}
	cell := map[string]topic.Combination{}
	for _, c := range ts.Matrix.Combinations {
		if !seen["m:"+c.Method] {
			seen["m:"+c.Method] = true
			methods = append(methods, c.Method)
		}
		if !seen["r:"+c.Resource] {
			seen["r:"+c.Resource] = true
			resources = append(resources, c.Resource)
		}
		cell[c.Resource+"/"+c.Method] = c
	}

	var b strings.Builder
	fmt.Fprintf(&b, "<!-- Generated by 'spectool render' from %s and %s – do not edit. -->\n", topic.MatrixFile, topic.GrammarFile)
	b.WriteString("# Method × Resource matrix\n\n")
	allowed := 0
	for _, c := range ts.Matrix.Combinations {
		if c.Allowed {
			allowed++
		}
	}
	fmt.Fprintf(&b, "Guideline baseline: `%s` · %d combinations, %d allowed · Grammar: [`topic.abnf`](../../topic/topic.abnf) · Vectors: [view](%sREADME.md)\n\n", ts.Matrix.Baseline, len(ts.Matrix.Combinations), allowed, matrixToVector)
	b.WriteString("Legend: ✓ allowed, ✗ not allowed. `S` = `<Source>`, `F` = `Filter`; `!` required, `?` optional, no letter = forbidden. The number in brackets counts the topic vectors that parse with this rule.\n\n")

	b.WriteString("## Overview\n\n| Resource / service |")
	for _, m := range methods {
		fmt.Fprintf(&b, " %s |", m)
	}
	b.WriteString("\n|---|")
	for range methods {
		b.WriteString(":---:|")
	}
	b.WriteString("\n")
	for _, r := range resources {
		fmt.Fprintf(&b, "| [%s](#%s) |", r, strings.ToLower(r))
		for _, m := range methods {
			c, ok := cell[r+"/"+m]
			switch {
			case !ok:
				b.WriteString(" |")
			case !c.Allowed:
				b.WriteString(" ✗ |")
			default:
				fmt.Fprintf(&b, " ✓ %s (%d) |", strings.TrimSpace(mark("S", c.Source)+" "+mark("F", c.Filter)), len(byRule[c.Rule]))
			}
		}
		b.WriteString("\n")
	}

	for _, r := range resources {
		kind := ""
		for _, m := range methods {
			if c, ok := cell[r+"/"+m]; ok {
				kind = c.Kind
				break
			}
		}
		fmt.Fprintf(&b, "\n## %s\n\nKind: %s\n\n", r, kind)
		b.WriteString("| Method | Allowed | Topic form | Rule | Source | Filter | Refs | Vectors (V-TOP-nnn) | Notes |\n|---|---|---|---|---|---|---|---|---|\n")
		for _, m := range methods {
			c, ok := cell[r+"/"+m]
			if !ok {
				continue
			}
			form, rule, src, flt, vecs := "–", "–", "–", "–", "–"
			if c.Allowed {
				form = "`" + topicForm(ts.Grammar, c.Rule) + "`"
				rule = "`" + c.Rule + "`"
				src, flt = c.Source, c.Filter
				if c.FilterRule != "" {
					flt += " (`" + c.FilterRule + "`)"
				}
				var links []string
				for _, id := range byRule[c.Rule] {
					links = append(links, fmt.Sprintf("[%s](%s%s#%s)", strings.TrimPrefix(id, "V-TOP-"), matrixToVector, viewOf[id], strings.ToLower(id)))
				}
				if len(links) > 0 {
					vecs = fmt.Sprintf("%d: %s", len(links), strings.Join(links, ", "))
				} else {
					vecs = "0"
				}
			}
			yes := "✗"
			if c.Allowed {
				yes = "✓"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", c.Method, yes, esc(form), rule, src, flt, strings.Join(c.Refs, ", "), vecs, esc(c.Notes))
		}
	}
	return b.String()
}

func mark(letter, v string) string {
	switch v {
	case topic.Required:
		return letter + "!"
	case topic.Optional:
		return letter + "?"
	}
	return ""
}

// formNames maps grammar rules to the placeholders of the guideline.
var formNames = map[string]string{
	"prefix":       "Oi4v2/<ServiceType>/<AppId>/",
	"source":       "<Source>",
	"tag":          "<Tag>",
	"context-name": "<Context.Name>",
	"event-filter": "<EventCategory>/<EventLevel>",
	"list-filter":  "<ResourceType>[/<Tag>]",
}

// topicForm renders a combination rule in the template notation of the
// guideline, e.g. "Oi4v2/<ServiceType>/<AppId>/Pub/Data[/<Source>[/<Tag>]]".
func topicForm(g *abnf.Grammar, rule string) string {
	r, ok := g.Rules[strings.ToLower(rule)]
	if !ok {
		return rule
	}
	var b strings.Builder
	var walk func(n abnf.Node) bool
	walk = func(n abnf.Node) bool {
		switch n := n.(type) {
		case abnf.Concat:
			for _, it := range n.Items {
				if !walk(it) {
					return false
				}
			}
		case abnf.Literal:
			b.WriteString(n.Text)
		case abnf.Ref:
			name, ok := formNames[n.Name]
			if !ok {
				b.WriteString("<" + n.Name + ">")
			} else {
				b.WriteString(name)
			}
		case abnf.Repeat:
			if n.Min != 0 || n.Max != 1 {
				return false
			}
			b.WriteString("[")
			if !walk(n.Item) {
				return false
			}
			b.WriteString("]")
		default:
			return false
		}
		return true
	}
	if !walk(r.Node) {
		return rule
	}
	return b.String()
}

func vectorFile(f vectors.File, ts *topic.Spec, areas map[string]bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- Generated by 'spectool render' from %s – do not edit. -->\n", f.Path)
	fmt.Fprintf(&b, "# Vectors: %s\n\n", strings.TrimSuffix(vectorViewName(f.Path), ".md"))
	fmt.Fprintf(&b, "Guideline baseline: `%s` · Kind: %s · %d vectors · [All vector files](README.md)\n\n%s\n\n", f.Baseline, f.Kind, len(f.Vectors), oneLine(f.Description))
	b.WriteString("| ID | Title | Expected | Result | Origin | Status |\n|---|---|---|---|---|---|\n")
	for _, v := range f.Vectors {
		fmt.Fprintf(&b, "| [%s](#%s) | %s | %s | %s | %s | %s |\n", v.ID, strings.ToLower(v.ID), esc(v.Title), v.Expected, esc(result(f.Kind, v)), esc(vectorOrigin(v)), v.Status)
	}
	for _, v := range f.Vectors {
		fmt.Fprintf(&b, "\n## %s\n\n**%s**\n\n", v.ID, esc(v.Title))
		for _, line := range fields(f.Kind, v, ts) {
			fmt.Fprintf(&b, "- %s\n", line)
		}
		fmt.Fprintf(&b, "- Expected: %s", v.Expected)
		if v.Reason != "" {
			fmt.Fprintf(&b, " – %s", oneLine(v.Reason))
		}
		b.WriteString("\n")
		if len(v.Reqs) > 0 {
			fmt.Fprintf(&b, "- Illustrates: %s\n", reqLinks(v.Reqs, areas))
		}
		if len(v.Violates) > 0 {
			fmt.Fprintf(&b, "- Violates: %s\n", reqLinks(v.Violates, areas))
		}
		fmt.Fprintf(&b, "- Origin: %s\n", vectorOrigin(v))
		if v.Origin.Original != "" {
			fmt.Fprintf(&b, "- Guideline original: %s\n", code(v.Origin.Original))
		}
		fmt.Fprintf(&b, "- Status: %s\n", v.Status)
		if v.Notes != "" {
			fmt.Fprintf(&b, "\nNotes: %s\n", oneLine(v.Notes))
		}
		if f.Kind == "payload" {
			payloadBlocks(&b, v)
		}
	}
	return b.String()
}

func result(kind string, v vectors.Vector) string {
	switch kind {
	case "topic":
		if v.Parse != nil {
			r := "rule " + v.Parse.Rule
			if len(v.Warnings) > 0 {
				r += ", warnings: " + strings.Join(v.Warnings, ", ")
			}
			return r
		}
		return "fails: " + v.Fails
	case "identification-link":
		if len(v.Violations) > 0 {
			return "violations: " + strings.Join(v.Violations, ", ")
		}
		return "ok"
	case "dnp-encoding":
		return "→ " + v.Output
	case "oi4identifier":
		if len(v.Violations) > 0 {
			return "violations: " + strings.Join(v.Violations, ", ")
		}
		return "→ " + v.Oi4Identifier
	case "payload":
		if len(v.Violates) > 0 {
			return "violates: " + strings.Join(v.Violates, ", ")
		}
		return "ok"
	}
	return ""
}

func fields(kind string, v vectors.Vector, ts *topic.Spec) []string {
	var out []string
	add := func(label, val string) {
		if val != "" {
			out = append(out, label+": "+val)
		}
	}
	addCode := func(label, val string) {
		if val != "" {
			add(label, code(val))
		}
	}
	switch kind {
	case "topic":
		add("Topic", code(v.Topic))
		if p := v.Parse; p != nil {
			add("Rule", fmt.Sprintf("`%s` ([matrix](%s#%s))", p.Rule, vectorToMatrix, strings.ToLower(p.Resource)))
			add("ServiceType · Method · Resource", fmt.Sprintf("%s · %s · %s", p.ServiceType, p.Method, p.Resource))
			add("AppId", code(p.AppIDIL)+" (decoded)")
			if p.Source != "" {
				add("Source", code(p.SourceIL)+" (decoded)")
			}
			if p.Filter != "" {
				f := code(p.Filter)
				if len(p.FilterValues) > 0 {
					var vals []string
					for _, fv := range p.FilterValues {
						vals = append(vals, code(fv))
					}
					f += " – decoded levels: " + strings.Join(vals, " / ")
				}
				add("Filter", f)
			}
		}
		add("Fails", v.Fails)
		if len(v.Warnings) > 0 {
			add("Warnings", strings.Join(v.Warnings, ", "))
		}
	case "identification-link":
		if v.IL != nil {
			add("Identification Link", code(*v.IL))
		}
		addCode("Encoded (topic element)", v.Encoded)
		if len(v.Violations) > 0 {
			add("Violations", strings.Join(v.Violations, ", "))
		}
	case "dnp-encoding":
		add("Input", code(v.Input))
		add("Output", code(v.Output))
	case "oi4identifier":
		add("ManufacturerUri", code(v.ManufacturerURI))
		add("Model", code(v.Model))
		add("ProductCode", code(v.ProductCode))
		add("SerialNumber", code(v.SerialNumber))
		addCode("Oi4Identifier", v.Oi4Identifier)
		if len(v.Violations) > 0 {
			add("Violations", strings.Join(v.Violations, ", "))
		}
	case "payload":
		if v.Object != "" {
			add("Object", code(v.Object)+" (bare object, no message)")
		} else {
			add("Topic", code(v.Topic))
		}
		if v.Mode != "" {
			add("Validation mode", v.Mode)
		}
		if v.Object != "" {
			break
		}
		if res, err := ts.Analyze(v.Topic); err == nil && res.Valid {
			p := res.Parsed
			add("ServiceType · Method · Resource", fmt.Sprintf("%s · %s · %s ([matrix](%s#%s))", p.ServiceType, p.Method, p.Resource, vectorToMatrix, strings.ToLower(p.Resource)))
			add("AppId", code(p.AppIDIL)+" (decoded)")
			if p.Source != "" {
				add("Source", code(p.SourceIL)+" (decoded)")
			}
			if p.Filter != "" {
				add("Filter", code(p.Filter))
			}
		}
	}
	return out
}

// payloadBlocks renders the message, the guideline original and the edits of
// a payload vector.
func payloadBlocks(b *strings.Builder, v vectors.Vector) {
	fmt.Fprintf(b, "\nPayload:\n\n```json\n%s\n```\n", strings.TrimRight(v.Payload, "\n"))
	if len(v.Edits) == 0 {
		return
	}
	b.WriteString("\nEdits against the guideline example:\n\n| Target | Kind | Reason | SF |\n|---|---|---|---|\n")
	for _, e := range v.Edits {
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", strings.ReplaceAll(e.Target, "|", "\\|"), e.Kind, esc(oneLine(e.Reason)), strings.Join(e.SF, ", "))
	}
	if v.Original != "" {
		fmt.Fprintf(b, "\n<details><summary>Guideline original (%s)</summary>\n\n```json\n%s\n```\n\n</details>\n", v.Origin.Ref, strings.TrimRight(v.Original, "\n"))
	}
}

func vectorOrigin(v vectors.Vector) string {
	s := origin(v.Origin)
	if n := len(v.Edits); n > 0 {
		s += fmt.Sprintf(" (edited: %d change(s))", n)
	}
	return s
}

func origin(o vectors.Origin) string {
	s := o.Kind
	if o.Ref != "" {
		s += " " + o.Ref
	}
	if len(o.SF) > 0 {
		s += " (edited: " + strings.Join(o.SF, ", ") + ")"
	}
	return s
}

func reqLinks(ids []string, areas map[string]bool) string {
	var out []string
	for _, id := range ids {
		area := ""
		if i := strings.LastIndex(id, "-"); i > len("REQ-") {
			area = id[len("REQ-"):i]
		}
		if areas[area] {
			out = append(out, fmt.Sprintf("[%s](%s%s#%s)", id, vectorToReqs, viewName(area), strings.ToLower(id)))
		} else {
			out = append(out, id)
		}
	}
	return strings.Join(out, ", ")
}

// code renders a value as a Markdown code span (not for table cells). Values
// with non-printable characters, back-ticks or leading/trailing white space
// are shown as a quoted Go string literal instead, marked "(escaped)".
func code(s string) string {
	if s == "" {
		return "_(empty)_"
	}
	plain := strings.TrimSpace(s) == s
	for _, r := range s {
		if r == '`' || !unicode.IsPrint(r) {
			plain = false
			break
		}
	}
	if plain {
		return "`" + s + "`"
	}
	q := strconv.QuoteToGraphic(s)
	if strings.Contains(q, "`") {
		return "`` " + q + " `` (escaped)"
	}
	return "`" + q + "` (escaped)"
}
