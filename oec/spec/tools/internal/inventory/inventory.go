// Package inventory generates and reads coverage/inventory.yaml: all
// candidates of normative statements in MG and RIG at one guideline commit.
package inventory

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"strings"

	"github.com/OI4/oec/spec/tools/internal/guideline"
	"github.com/OI4/oec/spec/tools/internal/yamlstrict"
	"go.yaml.in/yaml/v3"
)

// File is coverage/inventory.yaml.
type File struct {
	Baseline string           `json:"baseline" yaml:"baseline"`
	Note     string           `json:"note" yaml:"note"`
	Items    []guideline.Item `json:"items" yaml:"items"`
}

const note = "Generated by 'spectool inventory' – do not edit. Candidates of normative statements (MG 1.2); " +
	"each item is mapped to a requirement (inventory field) or classified in coverage/informative.yaml."

// Generate extracts the inventory from the guideline repository at root.
// If rev is empty, the short commit hash of root's HEAD is used.
func Generate(root, rev string) (*File, error) {
	if rev == "" {
		out, err := exec.Command("git", "-C", root, "rev-parse", "--short=7", "HEAD").Output()
		if err != nil {
			return nil, fmt.Errorf("cannot determine guideline commit (use -rev): %w", err)
		}
		rev = strings.TrimSpace(string(out))
	}
	files, err := guideline.LoadFiles(root)
	if err != nil {
		return nil, err
	}
	inv := &File{Baseline: rev, Note: note}
	seen := map[string]string{}
	for _, f := range files {
		for _, it := range guideline.Extract(f) {
			if prev, dup := seen[it.Key]; dup {
				return nil, fmt.Errorf("inventory key collision %s (%s and %s:%d)", it.Key, prev, it.File, it.Line)
			}
			seen[it.Key] = fmt.Sprintf("%s:%d", it.File, it.Line)
			inv.Items = append(inv.Items, it)
		}
	}
	return inv, nil
}

// Marshal renders the inventory as YAML that passes the strict loader.
func (f *File) Marshal() ([]byte, error) {
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(f); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	if _, err := yamlstrict.Load(buf.Bytes()); err != nil {
		return nil, fmt.Errorf("generated inventory is not strict YAML: %w", err)
	}
	return buf.Bytes(), nil
}

// Load reads an inventory file.
func Load(path string) (*File, error) {
	v, err := yamlstrict.LoadFile(path)
	if err != nil {
		return nil, err
	}
	var f File
	if err := yamlstrict.Decode(v, &f); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &f, nil
}

// Write stores the inventory at path.
func (f *File) Write(path string) error {
	data, err := f.Marshal()
	if err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

// ByKey indexes the items by key.
func (f *File) ByKey() map[string]guideline.Item {
	m := make(map[string]guideline.Item, len(f.Items))
	for _, it := range f.Items {
		m[it.Key] = it
	}
	return m
}
