// Package coverage relates the inventory of normative statements to the
// catalog: every item is either covered by a requirement or classified as
// informative (ADR-0018).
package coverage

import (
	"fmt"
	"sort"
	"strings"

	"github.com/OI4/oec/spec/tools/internal/catalog"
	"github.com/OI4/oec/spec/tools/internal/guideline"
	"github.com/OI4/oec/spec/tools/internal/inventory"
)

// AreaStats summarises one area.
type AreaStats struct {
	Area        catalog.Area
	Total       int
	Covered     int
	Informative int
	Open        []guideline.Item
}

// Result is the coverage of the whole inventory.
type Result struct {
	Baseline   string
	Areas      []*AreaStats
	Unassigned []guideline.Item
	Problems   []string
}

// Compute maps every inventory item to its area and status.
func Compute(s *catalog.Spec, inv *inventory.File) *Result {
	res := &Result{Baseline: inv.Baseline}
	if inv.Baseline != s.Areas.Baseline {
		res.Problems = append(res.Problems, fmt.Sprintf("inventory baseline %s differs from catalog baseline %s – regenerate the inventory", inv.Baseline, s.Areas.Baseline))
	}
	stats := map[string]*AreaStats{}
	for _, a := range s.Areas.Areas {
		st := &AreaStats{Area: a}
		stats[a.Code] = st
		res.Areas = append(res.Areas, st)
	}
	covered := map[string]bool{}
	for _, r := range s.Requirements() {
		for _, k := range r.Inventory {
			covered[k] = true
		}
	}
	info := map[string]bool{}
	for _, it := range s.Informative.Items {
		info[it.Key] = true
	}
	for _, it := range inv.Items {
		code := s.AreaOf(it.Section)
		st := stats[code]
		if st == nil {
			res.Unassigned = append(res.Unassigned, it)
			continue
		}
		st.Total++
		switch {
		case covered[it.Key]:
			st.Covered++
		case info[it.Key]:
			st.Informative++
		default:
			st.Open = append(st.Open, it)
		}
	}
	if len(res.Unassigned) > 0 {
		secs := map[string]bool{}
		for _, it := range res.Unassigned {
			secs[it.Section] = true
		}
		var l []string
		for k := range secs {
			l = append(l, k)
		}
		sort.Strings(l)
		res.Problems = append(res.Problems, "sections without area in areas.yaml: "+strings.Join(l, ", "))
	}
	for _, st := range res.Areas {
		if st.Area.Status != "planned" && len(st.Open) > 0 {
			res.Problems = append(res.Problems, fmt.Sprintf("area %s is %s but has %d unmapped inventory items", st.Area.Code, st.Area.Status, len(st.Open)))
		}
	}
	return res
}

// Report renders coverage/report.md.
func (r *Result) Report() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by 'spectool coverage' – do not edit. -->\n# Coverage of the guideline by the requirements catalog\n\n")
	fmt.Fprintf(&b, "Guideline baseline: `%s`. An inventory item is a candidate of a normative statement (MG 1.2) extracted by `spectool inventory`; it is either covered by a requirement or classified as informative in `coverage/informative.yaml`.\n\n", r.Baseline)
	b.WriteString("| Area | Cycle | Status | Items | Covered | Informative | Open |\n|---|---|---|---:|---:|---:|---:|\n")
	var tot, cov, inf, open int
	for _, st := range r.Areas {
		fmt.Fprintf(&b, "| %s | %s | %s | %d | %d | %d | %d |\n", st.Area.Code, st.Area.Cycle, st.Area.Status, st.Total, st.Covered, st.Informative, len(st.Open))
		tot += st.Total
		cov += st.Covered
		inf += st.Informative
		open += len(st.Open)
	}
	fmt.Fprintf(&b, "| **Total** | | | %d | %d | %d | %d |\n", tot, cov, inf, open)
	if len(r.Problems) > 0 {
		b.WriteString("\n## Problems\n\n")
		for _, p := range r.Problems {
			fmt.Fprintf(&b, "- %s\n", p)
		}
	}
	for _, st := range r.Areas {
		if st.Area.Status == "planned" || len(st.Open) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## Open items – %s\n\n", st.Area.Code)
		for _, it := range st.Open {
			fmt.Fprintf(&b, "- `%s` (%s:%d): %s\n", it.Key, it.File, it.Line, it.Text)
		}
	}
	return b.String()
}
