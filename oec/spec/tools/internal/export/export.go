// Package export writes JSON copies of the language-neutral spec data for
// consumers without a YAML parser: the Rust SDK (D2) and the micro SDK (D9)
// read the test vectors and the Method x Resource matrix from export/
// (ADR-0026). The YAML files stay the source of truth; 'spectool render'
// regenerates the copies and 'render -check' fails on stale ones.
package export

import (
	"bytes"
	"encoding/json"
	"path"
	"strings"

	"github.com/OI4/oec/spec/tools/internal/topic"
	"github.com/OI4/oec/spec/tools/internal/vectors"
)

// Paths of the exported files inside the spec directory.
const (
	Dir        = "export"
	VectorDir  = Dir + "/vectors"
	MatrixDir  = Dir + "/matrix"
	MatrixFile = MatrixDir + "/method-resource.json"
)

type header struct {
	Comment string `json:"$comment"`
	Source  string `json:"source"`
}

type vectorFile struct {
	header
	vectors.File
}

type matrixFile struct {
	header
	topic.Matrix
}

func comment(src string) header {
	return header{
		Comment: "Generated by 'spectool render' from " + src + " - do not edit.",
		Source:  src,
	}
}

// VectorName returns the export path of a vector file, e.g.
// vectors/il/dnp-encoding.yaml -> export/vectors/il-dnp-encoding.json.
func VectorName(p string) string {
	rel := strings.TrimPrefix(p, vectors.Dir+"/")
	return VectorDir + "/" + strings.ReplaceAll(strings.TrimSuffix(rel, path.Ext(rel)), "/", "-") + ".json"
}

// Files returns the exported files (relative path -> content).
func Files(ts *topic.Spec, files []vectors.File) (map[string]string, error) {
	out := map[string]string{}
	m, err := marshal(matrixFile{comment(topic.MatrixFile), ts.Matrix})
	if err != nil {
		return nil, err
	}
	out[MatrixFile] = m
	for _, f := range files {
		v, err := marshal(vectorFile{comment(f.Path), f})
		if err != nil {
			return nil, err
		}
		out[VectorName(f.Path)] = v
	}
	return out, nil
}

func marshal(v any) (string, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return "", err
	}
	return b.String(), nil
}
