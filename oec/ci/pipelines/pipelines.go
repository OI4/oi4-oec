// Package pipelines defines the CI workflows of the OEC monorepo
// (ADR-0032): the pinned actions, the hosted runners and the workflows that
// cmd/cigen renders into .github/workflows of the workspace repository.
//
// The workflows only set up tools and call the scripts of the local gate
// (oec/check.sh and oec/ci/*.sh); the tool versions live in
// oec/ci/versions.sh.
package pipelines

import "github.com/OI4/oec/ci/gha"

// The actions, pinned to the commit SHA of a release (ADR-0032 §4).
var (
	Checkout       = gha.Action{Repo: "actions/checkout", SHA: "3d3c42e5aac5ba805825da76410c181273ba90b1", Tag: "v7.0.1"}
	SetupGo        = gha.Action{Repo: "actions/setup-go", SHA: "b7ad1dad31e06c5925ef5d2fc7ad053ef454303e", Tag: "v7.0.0"}
	Cache          = gha.Action{Repo: "actions/cache", SHA: "55cc8345863c7cc4c66a329aec7e433d2d1c52a9", Tag: "v6.1.0"}
	UploadArtifact = gha.Action{Repo: "actions/upload-artifact", SHA: "cf430e030ddbb5b0abf93d22962f4752f3646cd9", Tag: "v7.0.2"}
	// release.yml (C-109): the release job takes the parts of its own run.
	DownloadArtifact = gha.Action{Repo: "actions/download-artifact", SHA: "9000827ccba6bdab643e8b6fd33ac0654aef8333", Tag: "v8.0.2"}
)

// Runner is a GitHub-hosted runner image.
type Runner struct{ Label, OS, Arch string }

// Runners are the hosted runners the workflows may use (ADR-0032 §6).
var Runners = []Runner{
	{"ubuntu-24.04", "linux", "amd64"},
	{"ubuntu-24.04-arm", "linux", "arm64"},
	{"macos-15", "darwin", "arm64"},
	{"macos-15-intel", "darwin", "amd64"},
	{"windows-2025", "windows", "amd64"},
	{"windows-11-arm", "windows", "arm64"},
}

// The guideline repository, checked out next to oec/ as in the local
// workspace (the inventory check of gate step 1 and docscheck of step 10).
const (
	GuidelineRepo   = "OI4/oi4-oec-documentation"
	GuidelineRef    = "feature/spec-findings"
	GuidelinePath   = "oi4-oec-documentation"
	GuidelineSecret = "OEC_GUIDELINE_TOKEN"
)

// The publishing step of release.yml (ADR-0034, C-110): the deployment
// environment whose required reviewers approve each publication, and its
// secret, the write token for OI4/oec and ghcr.io/oi4.
const (
	ReleaseEnvironment = "release"
	ReleaseSecret      = "OEC_RELEASE_TOKEN"
)

// Policy is the CI policy of ADR-0032 §4 with the pins above.
func Policy() gha.Policy {
	runners := map[string]bool{}
	for _, r := range Runners {
		runners[r.Label] = true
	}
	return gha.Policy{
		Actions: []gha.Action{Checkout, SetupGo, Cache, UploadArtifact, DownloadArtifact},
		Runners: runners,
		Secrets: map[string]gha.SecretUse{
			GuidelineSecret: {ActionRepo: Checkout.Repo, WithKey: "token"},
			ReleaseSecret:   {Environment: ReleaseEnvironment, EnvKey: ReleaseSecret},
		},
		MaxTimeout: 240,
	}
}

// Workflows returns every workflow of the repository.
func Workflows() []gha.Workflow {
	return []gha.Workflow{Gate(), Conformance(), SDK(), Micro(), Images(), SupplyChain(), Release()}
}

func header(lines ...string) []string {
	return append([]string{
		"Generated by oec/ci/cmd/cigen from oec/ci/pipelines (ADR-0032), do not edit:",
		"cd oec/ci && go run ./cmd/cigen (gate step 11 checks that this file is current).",
		"",
	}, lines...)
}

func base(file, name string, comment []string, jobs ...gha.Job) gha.Workflow {
	return gha.Workflow{
		File:         file,
		Comment:      comment,
		Name:         name,
		PushBranches: []string{"main"},
		PullRequest:  true,
		PathsIgnore:  []string{"project/**"}, // documentation only: no CI (C-111 D-3 (a))
		Dispatch:     true,
		Permissions:  []gha.KV{{Key: "contents", Value: "read"}},
		Concurrency:  gha.Concurrency{Group: "${{ github.workflow }}-${{ github.ref }}", CancelInProgress: true},
		Env:          []gha.KV{{Key: "GOTOOLCHAIN", Value: "auto"}, {Key: "CARGO_TERM_COLOR", Value: "never"}},
		Jobs:         jobs,
	}
}

func checkout() gha.Step {
	return gha.Step{Name: "Check out", Uses: Checkout, With: []gha.KV{{Key: "persist-credentials", Value: "false"}}}
}

func checkoutGuideline() gha.Step {
	return gha.Step{
		Name: "Check out the guideline (" + GuidelineRef + ")",
		Uses: Checkout,
		With: []gha.KV{
			{Key: "repository", Value: GuidelineRepo},
			{Key: "ref", Value: GuidelineRef},
			{Key: "path", Value: GuidelinePath},
			{Key: "fetch-depth", Value: "0"},
			{Key: "persist-credentials", Value: "false"},
			{Key: "token", Value: "${{ secrets." + GuidelineSecret + " || github.token }}"},
		},
	}
}

func setupGo(modFile, depFiles string) gha.Step {
	return gha.Step{Name: "Set up Go", Uses: SetupGo, With: []gha.KV{
		{Key: "go-version-file", Value: modFile},
		{Key: "cache-dependency-path", Value: depFiles},
	}}
}

func run(name, cmd string) gha.Step { return gha.Step{Name: name, Run: cmd} }

func matrix(labels ...string) []gha.Entry {
	var m []gha.Entry
	for _, l := range labels {
		m = append(m, gha.Entry{{Key: "os", Value: l}})
	}
	return m
}

// Gate runs the whole local gate oec/check.sh on Linux amd64/arm64 and
// macOS arm64, and actionlint on the workflows.
func Gate() gha.Workflow {
	m := []gha.Entry{
		// clang on Linux: clang --analyze of sdk/micro/check.sh, the same
		// compiler for cgo, CMake and the sanitizers as on macOS.
		{{Key: "os", Value: "ubuntu-24.04"}, {Key: "cc", Value: "clang"}},
		{{Key: "os", Value: "ubuntu-24.04-arm"}, {Key: "cc", Value: "clang"}},
		{{Key: "os", Value: "macos-15"}, {Key: "cc", Value: "cc"}},
	}
	gate := gha.Job{
		ID:             "gate",
		Name:           "oec/check.sh (${{ matrix.os }})",
		RunsOn:         "${{ matrix.os }}",
		Matrix:         m,
		TimeoutMinutes: 180,
		// No incremental cache: the debug targets of the gate stay smaller
		// on the runner disk (C-104 addendum 3).
		Env: []gha.KV{{Key: "CC", Value: "${{ matrix.cc }}"}, {Key: "CARGO_INCREMENTAL", Value: "0"}},
		Steps: []gha.Step{
			checkout(),
			checkoutGuideline(),
			setupGo("oec/conformance/go.mod", "oec/**/go.sum"),
			{
				Name: "Cache the cargo tools and crates",
				Uses: Cache,
				With: []gha.KV{
					{Key: "path", Value: "~/.oec-tools\n~/.cargo/registry\n"},
					{Key: "key", Value: "oec-cargo-${{ runner.os }}-${{ runner.arch }}-${{ hashFiles('oec/ci/versions.sh', 'oec/**/Cargo.lock') }}"},
					{Key: "restore-keys", Value: "oec-cargo-${{ runner.os }}-${{ runner.arch }}-"},
				},
			},
			run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
			run("Install the system packages (Linux)", "oec/ci/packages.sh"),
			run("Install the tools of oec/ci/versions.sh", "oec/ci/setup-tools.sh"),
			run("Fetch the crates of every Cargo.lock", "oec/ci/fetch.sh"),
			run("Gate (oec/check.sh)", "oec/check.sh"),
		},
	}
	lint := gha.Job{
		ID:             "actionlint",
		Name:           "actionlint (.github/workflows)",
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 15,
		Steps: []gha.Step{
			checkout(),
			setupGo("oec/ci/go.mod", "oec/ci/go.mod"),
			run("actionlint (oec/ci/lint.sh)", "oec/ci/lint.sh"),
		},
	}
	return base("gate.yml", "gate", header(
		"The local gate oec/check.sh on Linux amd64/arm64 and macOS arm64, with the",
		"guideline repository next to oec/ as in the workspace; actionlint.",
	), gate, lint)
}

// Conformance runs the Go checks of D7/D8 (oec/conformance) on every
// runner and cross-builds oec-check and oec-infra as workflow artifacts.
func Conformance() gha.Workflow {
	var labels []string
	for _, r := range Runners {
		labels = append(labels, r.Label)
	}
	test := gha.Job{
		ID:             "test",
		Name:           "oec/conformance (${{ matrix.os }})",
		RunsOn:         "${{ matrix.os }}",
		Matrix:         matrix(labels...),
		TimeoutMinutes: 60,
		Steps: []gha.Step{
			checkout(),
			setupGo("oec/conformance/go.mod", "oec/conformance/go.sum"),
			run("gofmt, vet, test (oec/ci/conformance.sh)", "oec/ci/conformance.sh"),
		},
	}
	bin := gha.Job{
		ID:             "binaries",
		Name:           "oec-check and oec-infra binaries",
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 30,
		Steps: []gha.Step{
			checkout(),
			setupGo("oec/conformance/go.mod", "oec/conformance/go.sum"),
			run("Cross-build (oec/ci/binaries.sh)", "oec/ci/binaries.sh dist/conformance"),
			{
				Name: "Upload the binaries (workflow artifact, not a release)",
				Uses: UploadArtifact,
				With: []gha.KV{
					{Key: "name", Value: "oec-conformance-binaries"},
					{Key: "path", Value: "dist/conformance"},
					{Key: "if-no-files-found", Value: "error"},
					{Key: "retention-days", Value: "14"},
				},
			},
		},
	}
	return base("conformance.yml", "conformance", header(
		"D7 oec-check and D8 oec-infra: gofmt, vet and the tests of oec/conformance on",
		"Linux, macOS and Windows (amd64 and arm64), and the binaries for",
		"windows/linux/darwin x amd64/arm64 as a workflow artifact (no release).",
	), test, bin)
}

// sdkCache caches the crates of the SDK workspace; its own key prefix, the
// entry of gate.yml also holds cbindgen and cargo-deny.
func sdkCache() gha.Step {
	return gha.Step{
		Name: "Cache the crates",
		Uses: Cache,
		With: []gha.KV{
			{Key: "path", Value: "~/.cargo/registry\n"},
			{Key: "key", Value: "oec-sdk-${{ runner.os }}-${{ runner.arch }}-${{ hashFiles('oec/ci/versions.sh', 'oec/sdk/rust/Cargo.lock') }}"},
			{Key: "restore-keys", Value: "oec-sdk-${{ runner.os }}-${{ runner.arch }}-"},
		},
	}
}

func uploadLib(name, cond string) gha.Step {
	return gha.Step{
		Name: "Upload the prebuilt library (workflow artifact, not a release)",
		If:   cond,
		Uses: UploadArtifact,
		With: []gha.KV{
			{Key: "name", Value: name},
			{Key: "path", Value: "dist/sdk/" + name},
			{Key: "if-no-files-found", Value: "error"},
			{Key: "retention-days", Value: "14"},
		},
	}
}

// SDK is the SDK platform matrix (ADR-0032 §6, C-105): the Rust SDK and
// its C ABI natively on every runner (Linux/macOS/Windows x amd64/arm64,
// Windows with MSVC), the Go SDK on every runner with a cgo toolchain
// (Windows amd64 with MinGW), ARMv7 Linux as a cross build (best effort,
// Q-008), and the prebuilt liboec_ffi of each target as a workflow
// artifact (no release, Q-011).
func SDK() gha.Workflow {
	// target: the Rust host target of the runner, checked by sdk-rust.sh;
	// cc: OEC_CI_CC, clang on Linux as in gate.yml (the sanitizers of the
	// C tests), the clang of LLVM for the C smoke test on Windows.
	entry := func(os, target, cc string) gha.Entry {
		return gha.Entry{{Key: "os", Value: os}, {Key: "target", Value: target}, {Key: "cc", Value: cc}}
	}
	setup := []gha.Step{
		run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
		run("Install the system packages (Linux)", "oec/ci/packages.sh"),
		run("Install the Rust toolchain of oec/ci/versions.sh", "oec/ci/setup-tools.sh --toolchain"),
	}
	rust := gha.Job{
		ID:     "rust",
		Name:   "Rust SDK and C ABI (${{ matrix.target }})",
		RunsOn: "${{ matrix.os }}",
		Matrix: []gha.Entry{
			entry("ubuntu-24.04", "x86_64-unknown-linux-gnu", "clang"),
			entry("ubuntu-24.04-arm", "aarch64-unknown-linux-gnu", "clang"),
			entry("macos-15", "aarch64-apple-darwin", "cc"),
			entry("macos-15-intel", "x86_64-apple-darwin", "cc"),
			entry("windows-2025", "x86_64-pc-windows-msvc", "clang"),
			entry("windows-11-arm", "aarch64-pc-windows-msvc", "clang"),
		},
		TimeoutMinutes: 120,
		Env: []gha.KV{
			{Key: "OEC_CI_TARGET", Value: "${{ matrix.target }}"},
			{Key: "OEC_CI_CC", Value: "${{ matrix.cc }}"},
			{Key: "CARGO_INCREMENTAL", Value: "0"},
		},
		Steps: append(append([]gha.Step{checkout(), sdkCache()}, setup...),
			run("Build and test (oec/ci/sdk-rust.sh)", "oec/ci/sdk-rust.sh dist/sdk"),
			uploadLib("liboec_ffi-${{ matrix.target }}", ""),
		),
	}
	goJob := gha.Job{
		ID:     "go",
		Name:   "Go SDK (${{ matrix.os }})",
		RunsOn: "${{ matrix.os }}",
		// cgo needs a C toolchain of the target: MinGW (x86-64) on
		// windows-2025, none for windows-11-arm.
		Matrix: []gha.Entry{
			entry("ubuntu-24.04", "x86_64-unknown-linux-gnu", "clang"),
			entry("ubuntu-24.04-arm", "aarch64-unknown-linux-gnu", "clang"),
			entry("macos-15", "aarch64-apple-darwin", "cc"),
			entry("macos-15-intel", "x86_64-apple-darwin", "cc"),
			entry("windows-2025", "x86_64-pc-windows-gnu", "gcc"),
		},
		TimeoutMinutes: 90,
		Env: []gha.KV{
			{Key: "OEC_CI_CC", Value: "${{ matrix.cc }}"},
			{Key: "CARGO_INCREMENTAL", Value: "0"},
		},
		Steps: append(append([]gha.Step{
			checkout(),
			setupGo("oec/sdk/go/go.mod", "oec/sdk/go/go.mod\noec/conformance/go.sum\n"),
			sdkCache(),
		}, setup...),
			run("Build and test (oec/ci/sdk-go.sh)", "oec/ci/sdk-go.sh dist/sdk"),
			uploadLib("liboec_ffi-x86_64-pc-windows-gnu", "runner.os == 'Windows'"),
		),
	}
	armv7 := gha.Job{
		ID:             "armv7",
		Name:           "ARMv7 Linux, best effort (cross build, qemu-arm)",
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 90,
		Env:            []gha.KV{{Key: "CARGO_INCREMENTAL", Value: "0"}},
		Steps: []gha.Step{
			checkout(),
			setupGo("oec/sdk/go/go.mod", "oec/sdk/go/go.mod\n"),
			sdkCache(),
			run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
			run("Install the system packages and the ARMv7 cross toolchain", "oec/ci/packages.sh --armv7"),
			run("Install the Rust toolchain of oec/ci/versions.sh", "oec/ci/setup-tools.sh --toolchain"),
			run("Cross-build and test (oec/ci/sdk-armv7.sh)", "oec/ci/sdk-armv7.sh dist/sdk"),
			uploadLib("liboec_ffi-armv7-unknown-linux-gnueabihf", ""),
		},
	}
	return base("sdk.yml", "sdk", header(
		"The SDK platform matrix: the Rust SDK and its C ABI on Linux, macOS and",
		"Windows (amd64 and arm64, Windows with MSVC), the Go SDK (Windows with",
		"MinGW), ARMv7 Linux as a cross build (best effort), and the prebuilt",
		"liboec_ffi of each target as a workflow artifact (no release).",
	), rust, goJob, armv7)
}

// microCache caches the crates of the SDK workspace that the micro jobs
// build go-testbroker from: downloads only, its own key prefix; cond: the
// runners that build it.
func microCache(cond string) gha.Step {
	return gha.Step{
		Name: "Cache the crates",
		If:   cond,
		Uses: Cache,
		With: []gha.KV{
			{Key: "path", Value: "~/.cargo/registry\n"},
			{Key: "key", Value: "oec-micro-${{ runner.os }}-${{ runner.arch }}-${{ hashFiles('oec/ci/versions.sh', 'oec/sdk/rust/Cargo.lock') }}"},
			{Key: "restore-keys", Value: "oec-micro-${{ runner.os }}-${{ runner.arch }}-"},
		},
	}
}

// Micro is the micro SDK workflow (ADR-0032 §6, C-106): the host checks of
// oec/sdk/micro/check.sh with GCC on Linux amd64/arm64 (the gate runs them
// with clang) and their portable part on Windows with MinGW, the ESP-IDF
// builds esp32, esp32s3 and qemu plus D7 Level 1/2/3 against the firmware
// in the Espressif QEMU, in the Espressif container pinned by digest, and
// the Arduino library on Arduino-ESP32 3.3 and 4.0 with the pinned
// arduino-cli (ADR-0030). No artifacts: the firmware is evidence only.
func Micro() gha.Workflow {
	entry := func(os string) gha.Entry {
		return gha.Entry{{Key: "os", Value: os}, {Key: "cc", Value: "gcc"}}
	}
	goSetup := setupGo("oec/sdk/micro/host/go.mod", "oec/sdk/micro/host/go.mod\noec/conformance/go.sum\n")
	host := gha.Job{
		ID:     "host",
		Name:   "Micro SDK host checks (${{ matrix.os }})",
		RunsOn: "${{ matrix.os }}",
		// GCC everywhere: the gate covers clang (Linux, macOS); on Windows
		// MinGW is the cgo compiler of the Go host runner.
		Matrix:         []gha.Entry{entry("ubuntu-24.04"), entry("ubuntu-24.04-arm"), entry("windows-2025")},
		TimeoutMinutes: 60,
		Env: []gha.KV{
			{Key: "OEC_CI_CC", Value: "${{ matrix.cc }}"},
			{Key: "CARGO_INCREMENTAL", Value: "0"},
		},
		Steps: []gha.Step{
			checkout(),
			goSetup,
			microCache("runner.os != 'Windows'"),
			run("Install the system packages (Linux)", "oec/ci/packages.sh"),
			{Name: "Install the Rust toolchain of oec/ci/versions.sh (go-testbroker, Linux)", If: "runner.os != 'Windows'",
				Run: "oec/ci/setup-tools.sh --toolchain"},
			run("Host checks (oec/ci/micro-host.sh)", "oec/ci/micro-host.sh"),
		},
	}
	idf := gha.Job{
		ID:             "esp-idf",
		Name:           "ESP-IDF esp32, esp32s3, qemu and QEMU D7 (Espressif container)",
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 120,
		Env:            []gha.KV{{Key: "CARGO_INCREMENTAL", Value: "0"}},
		Steps: []gha.Step{
			checkout(),
			goSetup,
			microCache(""),
			run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
			run("Install the Rust toolchain of oec/ci/versions.sh (go-testbroker)", "oec/ci/setup-tools.sh --toolchain"),
			run("Build and run D7 in QEMU (oec/ci/micro-esp-idf.sh)", "oec/ci/micro-esp-idf.sh"),
		},
	}
	arduino := gha.Job{
		ID:     "arduino",
		Name:   "Arduino library (Arduino-ESP32 ${{ matrix.core }})",
		RunsOn: "${{ matrix.os }}",
		Matrix: []gha.Entry{
			{{Key: "os", Value: "ubuntu-24.04"}, {Key: "core", Value: "3.3"}},
			{{Key: "os", Value: "ubuntu-24.04"}, {Key: "core", Value: "4.0"}},
		},
		TimeoutMinutes: 90,
		Env:            []gha.KV{{Key: "OECM_ARDUINO_CORE", Value: "${{ matrix.core }}"}},
		Steps: []gha.Step{
			checkout(),
			run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
			run("Build the examples (oec/ci/micro-arduino.sh)", "oec/ci/micro-arduino.sh"),
		},
	}
	return base("micro.yml", "micro", header(
		"The micro SDK: the host checks with GCC on Linux amd64/arm64 and Windows",
		"(MinGW), the ESP-IDF builds and D7 Level 1/2/3 in the Espressif QEMU",
		"(container pinned by digest), the Arduino library on Arduino-ESP32 3.3 and",
		"4.0 (pinned arduino-cli). No artifacts.",
	), host, idf, arduino)
}

// Images is the image workflow (ADR-0032 §6, C-107): on Linux amd64 and
// arm64 each runner builds the images of the three demos, of the OEC
// Registry and of the compliance tools for linux/amd64 and linux/arm64,
// judges them with D8 image (and the applications with D8 run on the native
// image), walks "Getting started" with the images, runs the live run of
// D7/D8 with the registry (TestRunDev on Linux) and, on amd64, tries the
// same with Podman. No image leaves the runner (Q-011): the artifact holds
// the D8 reports and logs only.
func Images() gha.Workflow {
	images := gha.Job{
		ID:             "images",
		Name:           "Images, Getting started, live D7/D8 (${{ matrix.os }})",
		RunsOn:         "${{ matrix.os }}",
		Matrix:         matrix("ubuntu-24.04", "ubuntu-24.04-arm"),
		TimeoutMinutes: 120,
		Steps: []gha.Step{
			checkout(),
			setupGo("oec/conformance/go.mod", "oec/conformance/go.sum\noec/dev/go.mod\n"),
			run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
			run("Build the images, D8 image and run (oec/ci/images.sh)", "oec/ci/images.sh dist/images"),
			run("Getting started with the images (oec/ci/getting-started.sh)", "oec/ci/getting-started.sh"),
			run("Live D7/D8 with the registry (oec/ci/live-infra.sh)", "oec/ci/live-infra.sh"),
			{Name: "Podman (oec/ci/podman.sh, amd64)", If: "matrix.os == 'ubuntu-24.04'", Run: "oec/ci/podman.sh dist/images"},
			{
				Name: "Upload the D8 reports and logs (no image)",
				If:   "always()",
				Uses: UploadArtifact,
				With: []gha.KV{
					{Key: "name", Value: "oec-images-reports-${{ matrix.os }}"},
					{Key: "path", Value: "dist/images\n!dist/images/*.oci.tar\n"},
					{Key: "if-no-files-found", Value: "warn"},
					{Key: "retention-days", Value: "14"},
				},
			},
		},
	}
	return base("images.yml", "images", header(
		"The images of the demos, the OEC Registry and the compliance tools for",
		"linux/amd64 and linux/arm64, judged by D8; Getting started with them, the",
		"live run of D7/D8 with the registry and Podman. Nothing is pushed: the",
		"artifact holds the D8 reports and logs only (Q-011).",
	), images)
}

// SupplyChain is the supply chain workflow (ADR-0032 amendment C-108): the
// SBOM (SPDX 2.3), the license texts and the license report of every
// deliverable as a workflow artifact (no release, Q-011), and the
// vulnerability check of the Go modules, the Cargo.locks and the npm
// packages of the Registry Web UI with the current advisory databases. No
// schedule yet: the weekly run comes with the first release (C-108 D-3 (a));
// until then the CI is paused (C-105 D-2).
func SupplyChain() gha.Workflow {
	sbom := gha.Job{
		ID:             "sbom",
		Name:           "SBOM and license report of every deliverable",
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 30,
		Steps: []gha.Step{
			checkout(),
			setupGo("oec/demos/go.mod", "oec/**/go.sum"),
			{
				Name: "Cache the crates",
				Uses: Cache,
				With: []gha.KV{
					{Key: "path", Value: "~/.cargo/registry\n"},
					{Key: "key", Value: "oec-supply-${{ runner.os }}-${{ runner.arch }}-${{ hashFiles('oec/ci/versions.sh', 'oec/**/Cargo.lock') }}"},
					{Key: "restore-keys", Value: "oec-supply-${{ runner.os }}-${{ runner.arch }}-"},
				},
			},
			run("Install the Rust toolchain of oec/ci/versions.sh", "oec/ci/setup-tools.sh --toolchain"),
			run("Fetch the crates of every Cargo.lock", "oec/ci/fetch.sh"),
			run("SBOM, license texts and license report (oec/ci/sbom.sh)", "oec/ci/sbom.sh dist/sbom"),
			{
				Name: "Upload the SBOMs (workflow artifact, not a release)",
				Uses: UploadArtifact,
				With: []gha.KV{
					{Key: "name", Value: "oec-sbom"},
					{Key: "path", Value: "dist/sbom"},
					{Key: "if-no-files-found", Value: "error"},
					{Key: "retention-days", Value: "14"},
				},
			},
		},
	}
	audit := gha.Job{
		ID:             "audit",
		Name:           "Vulnerability check (govulncheck, cargo deny, npm audit)",
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 45,
		Steps: []gha.Step{
			checkout(),
			setupGo("oec/conformance/go.mod", "oec/**/go.sum"),
			{
				Name: "Cache the cargo tools and crates",
				Uses: Cache,
				With: []gha.KV{
					{Key: "path", Value: "~/.oec-tools\n~/.cargo/registry\n"},
					{Key: "key", Value: "oec-audit-${{ runner.os }}-${{ runner.arch }}-${{ hashFiles('oec/ci/versions.sh', 'oec/**/Cargo.lock') }}"},
					{Key: "restore-keys", Value: "oec-audit-${{ runner.os }}-${{ runner.arch }}-"},
				},
			},
			run("Install the tools of oec/ci/versions.sh", "oec/ci/setup-tools.sh"),
			run("govulncheck, cargo deny check advisories, npm audit (oec/ci/audit.sh)", "oec/ci/audit.sh dist/audit"),
			{
				Name: "Upload the outputs of the checks",
				If:   "always()",
				Uses: UploadArtifact,
				With: []gha.KV{
					{Key: "name", Value: "oec-audit"},
					{Key: "path", Value: "dist/audit"},
					{Key: "if-no-files-found", Value: "warn"},
					{Key: "retention-days", Value: "14"},
				},
			},
		},
	}
	return base("supply-chain.yml", "supply-chain", header(
		"The SBOM (SPDX 2.3), license texts and license report of every deliverable",
		"as a workflow artifact (no release, Q-011), and the vulnerability check of",
		"the dependencies: govulncheck, cargo deny check advisories, npm audit.",
	), sbom, audit)
}

// releaseGo sets up the Go of modFile without the module cache of
// actions/setup-go: a release job uses no cache (ADR-0033 §5).
func releaseGo(modFile string) gha.Step {
	return gha.Step{Name: "Set up Go (no cache)", Uses: SetupGo, With: []gha.KV{
		{Key: "go-version-file", Value: modFile},
		{Key: "cache", Value: "false"},
	}}
}

func uploadPart(name string) gha.Step {
	return gha.Step{
		Name: "Upload the part (workflow artifact of this run)",
		Uses: UploadArtifact,
		With: []gha.KV{
			{Key: "name", Value: name},
			{Key: "path", Value: "dist/release"},
			{Key: "if-no-files-found", Value: "error"},
			{Key: "retention-days", Value: "7"},
		},
	}
}

// Release is the release workflow (ADR-0033, C-109): on a tag oec-v<version>
// or by hand, it builds every deliverable of the release train from one
// commit with oec/ci/release.sh – the prebuilt C ABI library for each
// target of the SDK matrix, the source archive, D7/D8 for six platforms,
// the micro SDK as an Arduino library, the schema bundle, the SBOMs, the
// images as OCI archives with their D8 reports – and assembles them with
// SHA256SUMS and the release notes into one workflow artifact. No caches.
// Every run checks the publication with a dry run of oec/ci/publish.sh. On
// a tag, the job publish – behind the environment release, whose reviewers
// approve each run (ADR-0034, C-110) – publishes the release of the same run
// on the channels of C-109 D-3 (a): the GitHub Release and the Go module
// tags of OI4/oec and the images on ghcr.io/oi4. crates.io, the ESP
// Component Registry and the Arduino Library Manager come later; the weekly
// schedule of supply-chain.yml comes with the first release (C-108 D-3 (a)).
func Release() gha.Workflow {
	entry := func(os, target string) gha.Entry {
		return gha.Entry{{Key: "os", Value: os}, {Key: "target", Value: target}}
	}
	const armv7 = "matrix.target == 'armv7-unknown-linux-gnueabihf'"
	ffi := gha.Job{
		ID:     "ffi",
		Name:   "liboec_ffi (${{ matrix.target }})",
		RunsOn: "${{ matrix.os }}",
		// The targets of release.sh (ffi_targets), each on its runner of sdk.yml.
		Matrix: []gha.Entry{
			entry("ubuntu-24.04", "x86_64-unknown-linux-gnu"),
			entry("ubuntu-24.04-arm", "aarch64-unknown-linux-gnu"),
			entry("ubuntu-24.04", "armv7-unknown-linux-gnueabihf"),
			entry("macos-15-intel", "x86_64-apple-darwin"),
			entry("macos-15", "aarch64-apple-darwin"),
			entry("windows-2025", "x86_64-pc-windows-msvc"),
			entry("windows-11-arm", "aarch64-pc-windows-msvc"),
			entry("windows-2025", "x86_64-pc-windows-gnu"),
		},
		TimeoutMinutes: 90,
		Env: []gha.KV{
			{Key: "OEC_CI_TARGET", Value: "${{ matrix.target }}"},
			{Key: "CARGO_INCREMENTAL", Value: "0"},
		},
		Steps: []gha.Step{
			checkout(),
			run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
			{Name: "Install the system packages (Linux)", If: "!(" + armv7 + ")", Run: "oec/ci/packages.sh"},
			{Name: "Install the system packages and the ARMv7 cross toolchain", If: armv7, Run: "oec/ci/packages.sh --armv7"},
			run("Install the Rust toolchain of oec/ci/versions.sh", "oec/ci/setup-tools.sh --toolchain"),
			run("Build the library (oec/ci/release.sh ffi)", "oec/ci/release.sh dist/release ffi"),
			uploadPart("oec-release-ffi-${{ matrix.target }}"),
		},
	}
	dist := gha.Job{
		ID:             "dist",
		Name:           "Source, D7/D8, micro SDK, schema bundle, SBOMs",
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 60,
		Steps: []gha.Step{
			checkout(),
			releaseGo("oec/ci/go.mod"),
			run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
			run("Install the Rust toolchain of oec/ci/versions.sh", "oec/ci/setup-tools.sh --toolchain"),
			run("Fetch the crates of every Cargo.lock", "oec/ci/fetch.sh"),
			run("Build the parts (oec/ci/release.sh)", "oec/ci/release.sh dist/release source binaries micro schema sbom"),
			uploadPart("oec-release-dist"),
		},
	}
	images := gha.Job{
		ID:             "images",
		Name:           "Images as OCI archives, judged by D8",
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 120,
		Steps: []gha.Step{
			checkout(),
			releaseGo("oec/conformance/go.mod"),
			run("Free disk space (hosted Linux runners)", "oec/ci/disk.sh"),
			run("Build the images (oec/ci/release.sh images)", "oec/ci/release.sh dist/release images"),
			uploadPart("oec-release-images"),
		},
	}
	release := gha.Job{
		ID:             "release",
		Name:           "Assemble the release (SHA256SUMS, release notes)",
		Needs:          []string{"ffi", "dist", "images"},
		RunsOn:         "ubuntu-24.04",
		TimeoutMinutes: 30,
		Steps: []gha.Step{
			checkout(),
			releaseGo("oec/ci/go.mod"),
			{
				Name: "Download the parts of this run",
				Uses: DownloadArtifact,
				With: []gha.KV{
					{Key: "pattern", Value: "oec-release-*"},
					{Key: "path", Value: "dist/release"},
					{Key: "merge-multiple", Value: "true"},
				},
			},
			run("Assemble (oec/ci/release.sh assemble)", "oec/ci/release.sh dist/release assemble"),
			run("Check the publication (oec/ci/publish.sh, dry run)", "oec/ci/publish.sh dist/release"),
			{
				Name: "Upload the release (workflow artifact, not a release)",
				Uses: UploadArtifact,
				With: []gha.KV{
					{Key: "name", Value: "oec-release"},
					{Key: "path", Value: "dist/release"},
					{Key: "if-no-files-found", Value: "error"},
					{Key: "retention-days", Value: "30"},
				},
			},
		},
	}
	publish := gha.Job{
		ID:             "publish",
		Name:           "Publish the release (OI4/oec, ghcr.io/oi4)",
		Needs:          []string{"release"},
		If:             "github.ref_type == 'tag'",
		RunsOn:         "ubuntu-24.04",
		Environment:    ReleaseEnvironment,
		TimeoutMinutes: 60,
		Steps: []gha.Step{
			checkout(),
			releaseGo("oec/ci/go.mod"),
			{
				Name: "Download the release of this run",
				Uses: DownloadArtifact,
				With: []gha.KV{
					{Key: "name", Value: "oec-release"},
					{Key: "path", Value: "dist/release"},
				},
			},
			{
				Name: "Publish (oec/ci/publish.sh --publish)",
				Env: []gha.KV{
					{Key: ReleaseSecret, Value: "${{ secrets." + ReleaseSecret + " }}"},
					{Key: "OEC_RELEASE_USER", Value: "${{ vars.OEC_RELEASE_USER }}"},
				},
				Run: "oec/ci/publish.sh dist/release --publish",
			},
		},
	}
	w := base("release.yml", "release", header(
		"The release of the OEC deliverables (ADR-0033, ADR-0034): on a tag",
		"oec-v<version> or by hand, every deliverable is built from one commit",
		"with oec/ci/release.sh and assembled with SHA256SUMS and the release",
		"notes into the workflow artifact oec-release; publish.sh checks its",
		"publication (dry run). Only on a tag, the job publish – behind the",
		"environment release, approved by its reviewers – publishes it: the",
		"GitHub Release and the Go module tags of OI4/oec, the images on",
		"ghcr.io/oi4.",
	), ffi, dist, images, release, publish)
	w.PushBranches = nil
	w.PushTags = []string{"oec-v*"}
	w.PullRequest = false
	w.PathsIgnore = nil
	return w
}
