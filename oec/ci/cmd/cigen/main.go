// Command cigen renders the CI workflows of oec/ci/pipelines into
// .github/workflows of the workspace repository (ADR-0032 §3). With -check
// it renders nothing and fails if a workflow breaks the CI policy, a file
// differs from its rendering or the directory holds a workflow cigen does
// not generate (gate step 11).
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/OI4/oec/ci/gha"
	"github.com/OI4/oec/ci/pipelines"
)

func main() {
	out := flag.String("out", "../../.github/workflows", "workflow directory (default relative to oec/ci)")
	check := flag.Bool("check", false, "check that the files are current instead of writing them")
	flag.Parse()
	if err := run(*out, *check); err != nil {
		fmt.Fprintln(os.Stderr, "cigen:", err)
		os.Exit(1)
	}
}

func run(dir string, check bool) error {
	files, err := render(pipelines.Workflows(), pipelines.Policy())
	if err != nil {
		return err
	}
	if !check {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		for _, name := range sortedKeys(files) {
			if err := os.WriteFile(filepath.Join(dir, name), files[name], 0o644); err != nil {
				return err
			}
		}
		fmt.Printf("cigen: %d workflows written to %s\n", len(files), dir)
		return nil
	}
	var errs []error
	for _, name := range sortedKeys(files) {
		got, err := os.ReadFile(filepath.Join(dir, name))
		switch {
		case err != nil:
			errs = append(errs, fmt.Errorf("%s: %w", name, err))
		case !bytes.Equal(got, files[name]):
			errs = append(errs, fmt.Errorf("%s is outdated", name))
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if _, ok := files[e.Name()]; !ok {
			errs = append(errs, fmt.Errorf("%s is not generated by cigen: add it to oec/ci/pipelines or remove it", e.Name()))
		}
	}
	if len(errs) > 0 {
		return fmt.Errorf("%w\nrun: cd oec/ci && go run ./cmd/cigen", errors.Join(errs...))
	}
	fmt.Printf("cigen: %d workflows current (%s)\n", len(files), strings.Join(sortedKeys(files), ", "))
	return nil
}

func render(ws []gha.Workflow, p gha.Policy) (map[string][]byte, error) {
	files := map[string][]byte{}
	var errs []error
	for _, w := range ws {
		errs = append(errs, gha.Check(w, p)...)
		b, err := gha.Render(w)
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", w.File, err))
		}
		if _, dup := files[w.File]; dup {
			errs = append(errs, fmt.Errorf("%s: two workflows", w.File))
		}
		files[w.File] = b
	}
	return files, errors.Join(errs...)
}

func sortedKeys(m map[string][]byte) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
