// Command oecm-vecgen writes the C header with the shared test vectors of
// oec/spec/export/vectors for the micro SDK host tests (ADR-0030 §4).
//
//	go run ./cmd/oecm-vecgen [-vectors DIR] [-out FILE] [-check]
//
// With -check it fails if FILE differs from the generated text.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	vectors := flag.String("vectors", "../../../spec/export/vectors", "directory of the exported vectors")
	out := flag.String("out", "../tests/vectors_gen.h", "header to write")
	check := flag.Bool("check", false, "only check that the header is up to date")
	flag.Parse()
	text, err := generate(*vectors)
	if err != nil {
		fmt.Fprintln(os.Stderr, "oecm-vecgen:", err)
		os.Exit(1)
	}
	if *check {
		old, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(old, text) {
			fmt.Fprintf(os.Stderr, "oecm-vecgen: %s is stale; run go run ./cmd/oecm-vecgen\n", *out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, text, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "oecm-vecgen:", err)
		os.Exit(1)
	}
}

type vector map[string]any

func load(dir, name string) ([]vector, error) {
	raw, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		return nil, err
	}
	var f struct {
		Vectors []vector `json:"vectors"`
	}
	if err := json.Unmarshal(raw, &f); err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	if len(f.Vectors) == 0 {
		return nil, fmt.Errorf("%s: no vectors", name)
	}
	return f.Vectors, nil
}

// lit is a C string literal of s with every octet outside printable ASCII
// as a three-digit octal escape (a hex escape would swallow following hex
// digits).
func lit(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '?':
			b.WriteString(`\?`) // no trigraphs
		case c < 0x20 || c >= 0x7f:
			fmt.Fprintf(&b, "\\%03o", c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// vs is a vstr initializer: absent keys and JSON null give {NULL, 0}.
func vs(v vector, key string) string {
	s, ok := v[key].(string)
	if !ok {
		return "VS_NONE"
	}
	return "VS(" + lit(s) + ")"
}

func list(v vector, key string) string {
	items, _ := v[key].([]any)
	parts := make([]string, 0, len(items))
	for _, it := range items {
		s, _ := it.(string)
		parts = append(parts, s)
	}
	if len(parts) == 0 {
		return "VS(\"\")"
	}
	return "VS(" + lit(strings.Join(parts, ",")) + ")"
}

func valid(v vector) string {
	if v["expected"] == "valid" {
		return "true"
	}
	return "false"
}

func generate(dir string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`/* Generated by oec/sdk/micro/host/cmd/oecm-vecgen from
 * oec/spec/export/vectors (ADR-0030 §4). DO NOT EDIT. */
#ifndef OECM_VECTORS_GEN_H
#define OECM_VECTORS_GEN_H

#include <stdbool.h>
#include <stddef.h>

typedef struct vstr {
    const char *s; /* NULL: absent */
    size_t n;
} vstr;

#define VS(lit) {(lit), sizeof(lit) - 1}
#define VS_NONE {NULL, 0}

`)
	type file struct {
		name, typ, arr string
		fields         string
		row            func(vector) string
	}
	files := []file{
		{"il-identification-link.json", "vec_il", "vec_il_all",
			"vstr id; bool valid; vstr il; vstr encoded; vstr violations;",
			func(v vector) string {
				return fmt.Sprintf("%s, %s, %s, %s, %s", vs(v, "id"), valid(v), vs(v, "il"), vs(v, "encoded"), list(v, "violations"))
			}},
		{"il-oi4identifier.json", "vec_oid", "vec_oid_all",
			"vstr id; bool valid; vstr manufacturer_uri; vstr model; vstr product_code; vstr serial_number; vstr oi4identifier; vstr violations;",
			func(v vector) string {
				return fmt.Sprintf("%s, %s, %s, %s, %s, %s, %s, %s", vs(v, "id"), valid(v), vs(v, "manufacturer_uri"), vs(v, "model"),
					vs(v, "product_code"), vs(v, "serial_number"), vs(v, "oi4identifier"), list(v, "violations"))
			}},
		{"il-dnp-encoding.json", "vec_dnp", "vec_dnp_all",
			"vstr id; vstr input; vstr output;",
			func(v vector) string {
				return fmt.Sprintf("%s, %s, %s", vs(v, "id"), vs(v, "input"), vs(v, "output"))
			}},
	}
	topicFields := "vstr id; bool valid; vstr topic; vstr rule; vstr service_type; vstr app_id; vstr app_id_il; vstr method; vstr resource; vstr source; vstr source_il; vstr filter; vstr filter_values; vstr warnings; vstr fails;"
	topicRow := func(v vector) string {
		p, _ := v["parse"].(map[string]any)
		pv := vector(p)
		// filter_values joined with the unit separator 0x1f.
		fv := "VS_NONE"
		if items, ok := pv["filter_values"].([]any); ok {
			parts := make([]string, 0, len(items))
			for _, it := range items {
				s, _ := it.(string)
				parts = append(parts, s)
			}
			fv = "VS(" + lit(strings.Join(parts, "\x1f")) + ")"
		}
		return fmt.Sprintf("%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s",
			vs(v, "id"), valid(v), vs(v, "topic"), vs(pv, "rule"), vs(pv, "service_type"), vs(pv, "app_id"), vs(pv, "app_id_il"),
			vs(pv, "method"), vs(pv, "resource"), vs(pv, "source"), vs(pv, "source_il"), vs(pv, "filter"), fv,
			list(v, "warnings"), vs(v, "fails"))
	}
	for _, n := range []struct{ name, arr string }{
		{"topic-guideline.json", "vec_topic_guideline"},
		{"topic-valid.json", "vec_topic_valid"},
		{"topic-invalid.json", "vec_topic_invalid"},
	} {
		files = append(files, file{n.name, "vec_topic", n.arr, topicFields, topicRow})
	}
	declared := map[string]bool{}
	for _, f := range files {
		vecs, err := load(dir, f.name)
		if err != nil {
			return nil, err
		}
		sort.SliceStable(vecs, func(i, j int) bool { return fmt.Sprint(vecs[i]["id"]) < fmt.Sprint(vecs[j]["id"]) })
		if !declared[f.typ] {
			declared[f.typ] = true
			fmt.Fprintf(&b, "typedef struct %s {\n    %s\n} %s;\n\n", f.typ, strings.ReplaceAll(f.fields, "; ", ";\n    "), f.typ)
		}
		fmt.Fprintf(&b, "/* %s */\nstatic const %s %s[] = {\n", f.name, f.typ, f.arr)
		for _, v := range vecs {
			fmt.Fprintf(&b, "    {%s},\n", f.row(v))
		}
		fmt.Fprintf(&b, "};\n#define %s_COUNT %d\n\n", strings.ToUpper(f.arr), len(vecs))
	}
	b.WriteString("#endif /* OECM_VECTORS_GEN_H */\n")
	return b.Bytes(), nil
}
