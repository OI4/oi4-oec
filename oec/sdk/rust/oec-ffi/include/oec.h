/*
 * oec.h - C ABI of the OEC Rust SDK (D2, crate oec-ffi, ADR-0021).
 *
 * Contract:
 *  - Prefix oec_ for functions and types, OEC_ for constants. The protocol
 *    enums are integer types with OEC_ constants; a value out of range is
 *    refused with OEC_ERR_INVALID_ARGUMENT.
 *  - Opaque handles. oec_product, oec_builder, oec_app and
 *    oec_subscription are owned by the caller and released with their
 *    oec_*_free function (oec_builder_build consumes the builder). Child
 *    handles (oec_asset, oec_dataset, oec_config) are owned by their
 *    oec_app: they stay valid until the app is freed, also after the child
 *    is removed (then their calls fail), and are never freed on their own.
 *    A handle must not be used after, or concurrently with, its release.
 *  - Strings are NUL-terminated UTF-8. Input strings are borrowed for the
 *    call (the SDK copies them). Strings passed to a callback are borrowed
 *    for the callback. Strings returned to the caller are owned and
 *    released with oec_string_free; oec_last_error and oec_version return
 *    borrowed strings.
 *  - Structured values cross the ABI as JSON text (OPC UA JSON field
 *    values, DataSet payloads, Config definitions); no Rust layout is
 *    exposed except oec_received.
 *  - Errors: every fallible function returns oec_status. On error,
 *    oec_last_error() has a message for the calling thread until its next
 *    failing oec_ call; for OEC_ERR_STATUS, oec_last_status_code() has the
 *    Bad StatusCode of the responder. Rust panics never cross the ABI: they
 *    become OEC_ERR_PANIC and the app is unusable afterwards.
 *  - Threading: every function may be called from any thread. Callbacks
 *    (Set handlers, subscriptions) run on the thread that runs the app
 *    (the caller of oec_app_run or the SDK thread of oec_app_start), one
 *    at a time per app; the callbacks of oec_get run on its caller's
 *    thread before it returns. A callback must not block for long; inside
 *    a callback the blocking functions (oec_get, oec_set, oec_del,
 *    oec_new_data_set_writer_id, oec_app_run) and oec_app_free are refused
 *    with OEC_ERR_INVALID_STATE, every other function may be called.
 *    user_data is passed back unchanged and must be usable on the thread
 *    of the callback. No async in the ABI.
 *  - ABI versioning: OEC_ABI_VERSION changes on every incompatible change;
 *    oec_abi_version() reports the version of the loaded library.
 */

